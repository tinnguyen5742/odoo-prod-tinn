from odoo import api, fields, models


class PsWorkShiftSlot(models.Model):
    _name = 'ps.work.shift.slot'
    _description = 'Work Shift Slot'
    _rec_name = 'x_name'
    _order = 'x_date, id'
    _inherit = ['mail.thread', 'mail.activity.mixin']

    x_name = fields.Char(
        string='Name',
        compute='_compute_x_name',
        store=True,
        index=True,
    )
    x_employee_id = fields.Many2one(
        'hr.employee',
        string='Employee',
        required=True,
        ondelete='cascade',
        index=True,
        tracking=True,
    )
    x_date = fields.Date(
        string='Date',
        required=True,
        index=True,
        tracking=True,
    )
    x_shift_id = fields.Many2one(
        'ps.work.shift',
        string='Shift',
        required=True,
        tracking=True,
    )
    x_start_time = fields.Many2one(
        'ps.work.shift',
        string='Start Time',
    )
    x_end_time = fields.Many2one(
        'ps.work.shift',
        string='End Time',
    )
    x_shift_start_time = fields.Float(
        string='Shift Start Time',
        related='x_shift_id.x_start_time',
        readonly=True,
    )
    x_shift_end_time = fields.Float(
        string='Shift End Time',
        related='x_shift_id.x_end_time',
        readonly=True,
    )
    x_overtime_from = fields.Float(
        string='Overtime Start',
        compute='_compute_x_overtime_info',
        readonly=True,
    )
    x_overtime_to = fields.Float(
        string='Overtime End',
        compute='_compute_x_overtime_info',
        readonly=True,
    )
    x_overtime_hours = fields.Float(
        string='Overtime Hours',
        compute='_compute_x_overtime_info',
        readonly=True,
    )

    @api.depends('x_employee_id', 'x_date')
    def _compute_x_overtime_info(self):
        # Lấy thông tin tăng ca từ các phiếu đăng ký tăng ca đã xác nhận.
        # Nếu có nhiều phiếu trong cùng ngày: tổng hợp giờ bắt đầu sớm nhất,
        # giờ kết thúc muộn nhất và tổng số giờ tăng ca.
        OvertimeLine = self.env['ps.overtime.registration.line']
        for rec in self:
            rec.x_overtime_from = 0.0
            rec.x_overtime_to = 0.0
            rec.x_overtime_hours = 0.0
            if not rec.x_employee_id or not rec.x_date:
                continue
            lines = OvertimeLine.sudo().search([
                ('x_employee_id', '=', rec.x_employee_id.id),
                ('x_date_from', '=', rec.x_date),
                ('x_time_from', '!=', False),
                ('x_time_to', '!=', False),
                ('x_state', '=', 'confirmed'),
            ])
            if lines:
                rec.x_overtime_from = min(lines.mapped('x_time_from'))
                rec.x_overtime_to = max(lines.mapped('x_time_to'))
                rec.x_overtime_hours = sum(lines.mapped('x_overtime_hours'))

    def _recompute_overtime_for(self, employee_ids, dates):
        """Gọi lại compute thông tin tăng ca cho các slot theo nhân viên/ngày."""
        if not employee_ids or not dates:
            return
        slots = self.sudo().search([
            ('x_employee_id', 'in', list(employee_ids)),
            ('x_date', 'in', list(dates)),
        ])
        if slots:
            slots._compute_x_overtime_info()

    @api.depends('x_employee_id', 'x_shift_id', 'x_date')
    def _compute_x_name(self):
        for rec in self:
            rec.x_name = f'{rec.x_employee_id.name or ""} - {rec.x_shift_id.x_shift_name or ""} ({rec.x_date})'
    x_source = fields.Selection(
        [
            ('auto', 'Auto'),
            ('manual', 'Manual'),
        ],
        string='Source',
        default='auto',
        required=True,
        tracking=True,
        help='Auto: generated by the rotation cron. Manual: set by user, never overwritten.',
    )
    x_old_shift_id = fields.Many2one(
        'ps.work.shift',
        string='Old Shift',
        tracking=True,
        help='Shift before the shift change.',
    )
    x_change_reason = fields.Char(
        string='Change Reason',
        tracking=True,
        help='Reason for the shift change.',
    )
    x_change_date = fields.Date(
        string='Change Date',
        tracking=True,
        help='Date when the shift change was confirmed.',
    )
    x_shift_change_id = fields.Many2one(
        'ps.shift.change',
        string='Shift Change',
        tracking=True,
        help='Reference to the shift change ticket.',
    )
    x_company_id = fields.Many2one(
        'res.company',
        string='Company',
        default=lambda self: self.env.company,
        tracking=True,
    )

    _slot_unique = models.Constraint(
        "UNIQUE(x_employee_id, x_date)",
        "A shift slot already exists for this employee on this date.",
    )


class PsShiftSchedule(models.Model):
    _name = 'ps.shift.schedule'
    _description = 'Shift Schedule'
    _inherit = ['mail.thread', 'mail.activity.mixin']

    def _cron_generate_shift_slots(self, days_ahead=30):
        # Cron sinh lich ca tu cac dang ky lich lam viec da xac nhan.
        # Duoc giu lai de tuong thich voi cron cu; thuc te delegete cho registration.
        self.env['ps.work.schedule.registration']._cron_generate_slots_from_registration(days_ahead)
        return True
