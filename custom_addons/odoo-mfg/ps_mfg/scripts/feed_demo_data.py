    fg = products["TP-DESK-001"]

    # BoM v1
    bom_v1 = Bom.search(
        [
            ("product_tmpl_id", "=", fg.product_tmpl_id.id),
            ("version", "=", 1),
            ("company_id", "=", company.id),
        ],
        limit=1,
    )
    if not bom_v1:
        # Shared operations (công đoạn dùng chung) carry resources / costs.
        Operation = env["ps.mfg.operation"]
        op_specs = [
            ("OP-CUT-WELD", "Cắt phôi & Hàn khung",
             [("RES_CNC_01", 50000.0), ("RES_WELDER_01", 80000.0)]),
            ("OP-PAINT", "Sơn tĩnh điện", [("RES_PAINT_01", 60000.0)]),
            ("OP-ASSEMBLY", "Lắp ráp & Đóng gói", [("RES_ASSEMBLER_01", 40000.0)]),
        ]
        shared_ops = []
        for code, name, res_specs in op_specs:
            operation = Operation.search(
                [("code", "=", code), ("company_id", "=", company.id)], limit=1
            )
            if not operation:
                operation = Operation.create(
                    {
                        "code": code,
                        "name": name,
                        "company_id": company.id,
                        "resource_ids": [
                            Command.create(
                                {
                                    "resource_id": resources[res_code].id,
                                    "resource_cost": cost,
                                }
                            )
                            for res_code, cost in res_specs
                        ],
                    }
                )
            shared_ops.append(operation)

