"""Seed script for Patsoft Manufacturing (ps_mfg) demo and test data.

This script creates:
1. Master data (Cost items, Resources, Work Center, Products, Initial Inventory, BoMs v1 & v2).
2. Scenario 1: MO in Draft state (MO-DEMO-001) with BoM v1.
3. Scenario 2: MO Confirmed (MO-DEMO-004) with Move Order and Transfer Proposal in Pending Approval state (Chờ duyệt).
4. Scenario 3: MO In Progress (MO-DEMO-002) with approved transfer proposal, completed stock picking, and shift moves (tracked lot consumption).
5. Scenario 4: MO Completed (MO-DEMO-003) with completed transfer proposal, finished proposal (good receipts + scrap).
6. Scenario 5: WIP Closing (ps.mfg.wip) for current month.
"""

from datetime import date

from odoo import Command, fields


def _validate_proposal_pickings(proposal):
    """Validate stock pickings generated by an approved proposal to simulate stock fulfillment."""
    for picking in proposal.picking_ids.filtered(
        lambda p: p.state not in ("done", "cancel")
    ):
        if picking.state == "draft":
            picking.action_confirm()
        if picking.state not in ("assigned", "done", "cancel"):
            picking.action_assign()
        for move in picking.move_ids:
            if not move.quantity:
                move.quantity = move.product_uom_qty
            move.picked = True
        picking.button_validate()


